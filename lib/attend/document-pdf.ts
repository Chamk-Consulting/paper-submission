import "server-only";
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import type { RegistrationDoc } from "@/lib/attend/data";

/* Invoice / receipt PDF for an attendee registration (RG01). Same look as the submission receipt. */

const money = (cents: number, cur: string) => `${(cents / 100).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })} ${cur}`;

export async function registrationPdf(d: RegistrationDoc, kind: "invoice" | "receipt"): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const title = kind === "invoice" ? `Invoice ${d.invoice_number ?? d.number}` : `Receipt ${d.number}`;
  doc.setTitle(`Plenary ${title}`);
  const page = doc.addPage([595, 842]);
  const serif = await doc.embedFont(StandardFonts.TimesRoman);
  const sans = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const navy = rgb(0.055, 0.106, 0.239), muted = rgb(0.29, 0.32, 0.39), rule = rgb(0.85, 0.86, 0.89);
  const clean = (s: string) => s.replace(/[^\x20-\x7E -ÿ]/g, "?");
  let y = 780;
  const text = (s: string, x: number, yy: number, size = 11, font = sans, color = navy) => page.drawText(clean(s), { x, y: yy, size, font, color });
  const wrap = (s: string, size = 11, font = sans, color = navy, width = 475, x = 60) => {
    let cur = "";
    for (const w of clean(s).split(" ")) {
      if (font.widthOfTextAtSize(`${cur} ${w}`, size) > width) { text(cur, x, y, size, font, color); y -= size + 5; cur = w; } else cur = cur ? `${cur} ${w}` : w;
    }
    if (cur) { text(cur, x, y, size, font, color); y -= size + 5; }
  };

  page.drawCircle({ x: 68, y: 794, size: 8, borderColor: navy, borderWidth: 1 });
  page.drawCircle({ x: 68, y: 794, size: 2.2, color: rgb(0.95, 0.66, 0.23) });
  text("Plenary", 82, 788, 18, serif);
  y = 742;
  text(kind === "invoice" ? "INVOICE" : "PAYMENT RECEIPT", 60, y, 9, bold, muted); y -= 34;
  text(kind === "invoice" ? (d.invoice_number ?? d.number) : d.number, 60, y, 26, bold); y -= 22;
  wrap(`${d.venue_name}${d.location ? ` · ${d.location}` : ""}${d.starts_on ? ` · ${d.starts_on}${d.ends_on && d.ends_on !== d.starts_on ? ` – ${d.ends_on}` : ""}` : ""}`, 12, serif);
  y -= 10;

  const left: [string, string][] = [
    ["Registration", `${d.number} · ${d.reg_type}`],
    ["Attendee", [d.full_name, d.affiliation].filter(Boolean).join(" · ") || "—"],
    ["Issued", new Date(d.created_at).toISOString().slice(0, 10)],
  ];
  if (kind === "receipt") left.push(["Paid", d.paid_at ? new Date(d.paid_at).toISOString().slice(0, 10) : "Not paid yet"]);
  if (d.papers.length) left.push(["Papers covered", d.papers.map((p) => `#${String(p.number).padStart(4, "0")} ${p.title}`).join("; ")]);
  const b = d.billing ?? {};
  if (b.name || b.address || b.vat || b.po) left.push(["Bill to", [b.name, b.address, b.vat ? `VAT ${b.vat}` : null, b.po ? `PO ${b.po}` : null].filter(Boolean).join(" · ")]);
  for (const [k, v] of left) { text(k, 60, y, 9, bold, muted); y -= 13; wrap(v, 11); y -= 4; }

  y -= 8;
  page.drawLine({ start: { x: 60, y }, end: { x: 535, y }, thickness: 0.6, color: rule }); y -= 18;
  text("Item", 60, y, 9, bold, muted); text("Qty", 380, y, 9, bold, muted); text("Amount", 460, y, 9, bold, muted); y -= 16;
  const cur = d.currency ?? "";
  for (const it of d.items ?? []) {
    text(it.name, 60, y, 11); text(String(it.qty), 380, y, 11); text(money(it.unit_cents * it.qty, cur), 460, y, 11); y -= 18;
  }
  page.drawLine({ start: { x: 60, y: y + 6 }, end: { x: 535, y: y + 6 }, thickness: 0.6, color: rule }); y -= 12;
  text("Total", 60, y, 12, bold); text(money(d.amount_cents ?? 0, cur), 460, y, 12, bold); y -= 30;

  if (kind === "invoice") {
    wrap(d.paid_at ? "Status: paid — thank you." : "Status: awaiting payment. Quote the invoice number with your bank transfer. Bank details are sent by the organizers.", 10, sans, muted);
  } else {
    wrap(d.paid_at ? `Received with thanks${d.payment_method === "card" ? " (card)" : d.payment_method === "invoice" ? " (bank transfer)" : ""}.` : "This registration is not paid yet.", 10, sans, muted);
  }
  y -= 6;
  wrap("Generated by Plenary for the organizers of this event. Questions about payment go to the event's registration chair.", 9, sans, muted);
  return doc.save();
}
