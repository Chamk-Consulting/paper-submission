import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { loadSubmission } from "@/lib/submission/data";

// Submission receipt (SB08 "Download receipt"). Only authors can load the submission (RLS).
export async function GET(_: Request, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const ctx = await loadSubmission(id);
  if (!ctx || !ctx.sub.number) return new Response("Not found", { status: 404 });
  const { sub, venue, authors, files } = ctx;
  const doc = await PDFDocument.create();
  doc.setTitle(`Plenary receipt #${sub.number}`);
  const page = doc.addPage([595, 842]);
  const serif = await doc.embedFont(StandardFonts.TimesRoman);
  const sans = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const navy = rgb(0.055, 0.106, 0.239), muted = rgb(0.29, 0.32, 0.39);
  let y = 780;
  const clean = (s: string) => s.replace(/[^\x20-\x7E -ÿ]/g, "?");
  const line = (text: string, size = 11, font = sans, color = navy, gap = 6) => {
    const words = clean(text).split(" "); let cur = "";
    for (const w of words) {
      if (font.widthOfTextAtSize(`${cur} ${w}`, size) > 475) { page.drawText(cur, { x: 60, y, size, font, color }); y -= size + gap; cur = w; } else cur = cur ? `${cur} ${w}` : w;
    }
    if (cur) { page.drawText(cur, { x: 60, y, size, font, color }); y -= size + gap; }
  };
  page.drawCircle({ x: 68, y: 794, size: 8, borderColor: navy, borderWidth: 1 });
  page.drawCircle({ x: 68, y: 794, size: 2.2, color: rgb(0.95, 0.66, 0.23) });
  page.drawText("Plenary", { x: 82, y: 788, size: 18, font: serif, color: navy });
  y = 740;
  line("SUBMISSION RECEIPT", 9, bold, muted);
  line(`#${String(sub.number).padStart(4, "0")}`, 30, bold, navy, 10);
  line(sub.title, 16, serif, navy, 6);
  y -= 8;
  const rows: [string, string][] = [
    ["Venue", `${venue.acr} — ${venue.name}`],
    ["Type", [sub.paperType, sub.track].filter(Boolean).join(" · ")],
    ["Submitted", sub.submittedAt ? `${new Date(sub.submittedAt).toUTCString()}` : "—"],
    ["Authors", authors.map((a) => `${a.position}. ${a.name}${a.corresponding ? " (corresponding)" : ""}`).join("; ")],
    ["Keywords", sub.keywords.join(", ")],
    ["Files", files.filter((f) => f.current || f.role !== "paper").map((f) => `${f.name} (${(f.size / 1048576).toFixed(1)} MB)`).join("; ")],
    ["Status", sub.stage === "withdrawn" ? "Withdrawn" : "Submitted — editable until the deadline"],
  ];
  for (const [k, v] of rows) { page.drawText(k, { x: 60, y, size: 10, font: bold, color: muted }); y -= 14; line(v || "—", 11, sans, navy, 4); y -= 6; }
  y -= 10;
  line("Quote the paper ID in any message to the organisers. This receipt was generated by Plenary.", 9, sans, muted);
  const bytes = await doc.save();
  return new Response(new Uint8Array(bytes), { headers: { "content-type": "application/pdf", "content-disposition": `attachment; filename="plenary-receipt-${sub.number}.pdf"`, "cache-control": "private, no-store" } });
}
