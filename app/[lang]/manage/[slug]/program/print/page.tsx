import type { Metadata } from "next";
import Link from "next/link";
import { getLocale, getT } from "@/lib/i18n/server";
import { requireEvent } from "@/lib/manage/data";
import { loadRooms, loadSessions } from "@/lib/manage/ops2-data";
import { fmtDayLabel, paperNo, utcToZoned } from "@/lib/manage/ops2-time";
import { INTL } from "@/lib/i18n/config";
import { ui } from "@/components/manage/ui";
import { PrintButton } from "@/components/manage/ops2/print-button";
import { Reveal } from "@/components/motion/reveal";
import { Bar, Line, Skeleton } from "@/components/skeletons/parts";

type P = { params: Promise<{ slug: string }> };

export async function generateMetadata(): Promise<Metadata> {
  const t = await getT();
  return { title: t("Program (print)") };
}

/* Printable program (EM29 "Export PDF"): one section per day, sessions in time order with rooms, chairs and talks. */
async function Inner({ params }: P) {
  const { slug } = await params;
  const ctx = await requireEvent(slug);
  const [t, locale] = [await getT(), await getLocale()];
  const [sessions, rooms] = await Promise.all([loadSessions(ctx.venue.id), loadRooms(ctx.venue.id)]);
  const tz = ctx.venue.timezone;
  const roomName = new Map(rooms.map((r) => [r.id, r.name]));
  const byDay = new Map<string, typeof sessions>();
  for (const s of sessions) { const d = utcToZoned(s.starts_at, tz).day; byDay.set(d, [...(byDay.get(d) ?? []), s]); }
  return (
    <main className="mx-auto max-w-[900px] bg-white px-6 py-8 text-[#121826] print:p-0">
      <div className="flex items-center justify-between gap-3 print:hidden">
        <Link href={`/manage/${slug}/program`} className="text-[14px]">← {t("Program builder")}</Link>
        <PrintButton />
      </div>
      <h1 className="mt-4 font-serif text-[34px] font-normal">{ctx.venue.name}</h1>
      <p className="m-0 text-[13px] text-[#4A5263]">{t("Program")} · {t("times in {tz}", { tz })}</p>
      {byDay.size === 0 ? <p className="mt-6">{t("No sessions yet.")}</p> : [...byDay.entries()].map(([d, list]) => (
        <section key={d} className="mt-8 break-inside-avoid-page">
          <h2 className="border-b border-[#121826] pb-1 font-serif text-[22px] font-normal">{fmtDayLabel(d, INTL[locale])}</h2>
          {list.map((s) => (
            <div key={s.id} className="mt-4 break-inside-avoid">
              <p className="m-0 text-[15px]"><strong className="font-mono">{utcToZoned(s.starts_at, tz).time}–{utcToZoned(s.ends_at, tz).time}</strong> · <span className="font-mono">{s.code}</span> · <strong>{s.title}</strong>{s.room_id ? ` · ${roomName.get(s.room_id) ?? ""}` : ""}</p>
              {s.chair ? <p className="m-0 text-[12px] text-[#4A5263]">{t("Chair:")} {s.chair}</p> : null}
              {s.talks.length ? (
                <table className="mt-1 w-full border-collapse text-[13px]">
                  <tbody>{s.talks.map((x) => (
                    <tr key={x.id}><td className="w-[60px] py-0.5 align-top font-mono text-[12px]">{x.starts_at ? utcToZoned(x.starts_at, tz).time : ""}</td><td className="w-[64px] py-0.5 align-top font-mono text-[12px]">{x.number ? paperNo(x.number) : ""}</td><td className="py-0.5">{x.title}{x.presenter ? <span className="text-[#4A5263]"> — {x.presenter}</span> : null}</td></tr>
                  ))}</tbody>
                </table>
              ) : null}
            </div>
          ))}
        </section>
      ))}
      <p className={`${ui.hint} mt-10`}>{t("Generated by Plenary.")}</p>
    </main>
  );
}

export default function Page(props: P) {
  return (
    <Reveal fallback={<main className="mx-auto max-w-[900px] px-6 py-8"><Skeleton><Line size={34} w={420} /><Line size={13} w={200} />{[1, 2, 3, 4, 5].map((i) => <Bar key={i} h={60} className="mt-4" />)}</Skeleton></main>}>
      <Inner {...props} />
    </Reveal>
  );
}
