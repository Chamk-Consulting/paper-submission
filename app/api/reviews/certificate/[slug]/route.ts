import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { createClient } from "@/lib/supabase/server";
import { getBrand } from "@/lib/config/brand";

// Reviewer certificate (RV04 / RV08 / RV01 "Download certificate"). Only the signed-in reviewer's own completed reviews count;
// public.reviewer_certificate returns null when there are none. Lives under /api so the locale proxy leaves it alone.

type Cert = { reviewer: string; orcid: string | null; venue: string; short: string; slug: string; starts_on: string | null; ends_on: string | null;
  reviews: number; first_at: string | null; last_at: string | null; chair: string | null };

const fmt = (iso: string | null) => (iso ? new Date(iso).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" }) : "");

export async function GET(_: Request, { params }: { params: Promise<{ slug: string }> }) {
  const brand = await getBrand();
  const { slug } = await params;
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return new Response("Sign in first", { status: 401 });
  const { data: venue } = await supabase.from("venues").select("id").eq("slug", slug).maybeSingle();
  if (!venue) return new Response("Not found", { status: 404 });
  const { data, error } = await supabase.rpc("reviewer_certificate", { p_venue: venue.id });
  const c = (error ? null : data) as Cert | null;
  if (!c) return new Response("No completed reviews at this venue", { status: 404 });

  const doc = await PDFDocument.create();
  doc.setTitle(`Reviewer certificate — ${c.short}`);
  const page = doc.addPage([842, 595]); // A4 landscape
  const serif = await doc.embedFont(StandardFonts.TimesRoman);
  const serifI = await doc.embedFont(StandardFonts.TimesRomanItalic);
  const sans = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const navy = rgb(0.055, 0.106, 0.239), muted = rgb(0.29, 0.32, 0.39), saffron = rgb(0.95, 0.66, 0.23);
  const clean = (s: string) => s.replace(/[^\x20-\x7E -ÿ]/g, "?");
  const center = (text: string, y: number, size: number, font = sans, color = navy) => {
    const t = clean(text); const w = font.widthOfTextAtSize(t, size);
    page.drawText(t, { x: (842 - w) / 2, y, size, font, color });
  };

  page.drawRectangle({ x: 24, y: 24, width: 794, height: 547, borderColor: navy, borderWidth: 1.2 });
  page.drawRectangle({ x: 24, y: 563, width: 794, height: 8, color: navy });
  page.drawCircle({ x: 397, y: 515, size: 11, borderColor: navy, borderWidth: 1.2 });
  page.drawCircle({ x: 397, y: 515, size: 3, color: saffron });
  page.drawText(`${brand}`, { x: 413, y: 508, size: 20, font: serif, color: navy });

  center("CERTIFICATE OF REVIEWING", 452, 11, bold, muted);
  center("This certifies that", 410, 15, serifI, muted);
  center(c.reviewer, 360, 40, serif, navy);
  if (c.orcid) center(`ORCID ${c.orcid}`, 336, 10, sans, muted);
  center(`completed ${c.reviews} ${c.reviews === 1 ? "review" : "reviews"} for`, 300, 15, serifI, muted);
  center(c.venue, 262, 24, serif, navy);
  const span = c.first_at && c.last_at ? (fmt(c.first_at) === fmt(c.last_at) ? fmt(c.last_at) : `${fmt(c.first_at)} – ${fmt(c.last_at)}`) : "";
  if (span) center(`Reviews submitted ${span}`, 232, 11, sans, muted);

  page.drawLine({ start: { x: 120, y: 130 }, end: { x: 340, y: 130 }, thickness: 0.8, color: muted });
  page.drawText(clean(c.chair ?? "The organizing committee"), { x: 120, y: 112, size: 12, font: serif, color: navy });
  page.drawText(c.chair ? "Chair, on behalf of the committee" : "", { x: 120, y: 98, size: 9, font: sans, color: muted });
  page.drawLine({ start: { x: 502, y: 130 }, end: { x: 722, y: 130 }, thickness: 0.8, color: muted });
  page.drawText(clean(fmt(new Date().toISOString())), { x: 502, y: 112, size: 12, font: serif, color: navy });
  page.drawText("Date issued", { x: 502, y: 98, size: 9, font: sans, color: muted });
  center(`Generated by ${brand} from the venue's review records. Reviews stay confidential; titles of reviewed papers are not listed.`, 50, 8, sans, muted);

  const bytes = await doc.save();
  return new Response(new Uint8Array(bytes), {
    headers: { "content-type": "application/pdf", "content-disposition": `attachment; filename="plenary-reviewer-certificate-${c.slug}.pdf"`, "cache-control": "private, no-store" },
  });
}
