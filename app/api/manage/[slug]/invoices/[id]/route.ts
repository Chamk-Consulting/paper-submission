import { createClient } from "@/lib/supabase/server";
import { MUTED, NAVY, PDFDocument, clean, fonts, logo, pdfResponse, wrap } from "@/lib/manage/orgtools-pdf";

/* BL01 — invoice PDF. Event owners only (billing_overview checks it). */

type Inv = { id: string; number: string; issued_on: string; due_on: string; description: string; amount_cents: number | null; currency: string; status: string; paid_at: string | null };
type Bill = { billing_name: string | null; vat_number: string | null; billing_address: string | null; po_number: string | null; invoice_email: string | null } | null;

export async function GET(_req: Request, { params }: { params: Promise<{ slug: string; id: string }> }) {
  const { slug, id } = await params;
  if (!/^[a-z0-9][a-z0-9-]{1,62}[a-z0-9]$/.test(slug) || !/^[0-9a-f-]{36}$/i.test(id)) return new Response("Not found", { status: 404 });
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return new Response("Sign in first", { status: 401 });
  const { data: venue } = await supabase.from("venues").select("id, name, short_name").eq("slug", slug).maybeSingle();
  if (!venue) return new Response("Not found", { status: 404 });
  const { data, error } = await supabase.rpc("billing_overview", { p_venue: venue.id });
  if (error || !data) return new Response("Not allowed", { status: 403 });
  const o = data as { billing: Bill; invoices: Inv[] };
  const inv = o.invoices.find((i) => i.id === id);
  if (!inv) return new Response("Not found", { status: 404 });
  const b = o.billing;

  const doc = await PDFDocument.create();
  doc.setTitle(`Plenary invoice ${inv.number}`);
  const page = doc.addPage([595, 842]);
  const { serif, sans, bold } = await fonts(doc);
  logo(page, 60, 788, serif);
  page.drawText("INVOICE", { x: 420, y: 790, size: 20, font: bold, color: NAVY });
  page.drawText(inv.number, { x: 420, y: 770, size: 11, font: sans, color: MUTED });
  const amount = inv.amount_cents === null ? "[PRICE]" : new Intl.NumberFormat("en-GB", { style: "currency", currency: inv.currency }).format(inv.amount_cents / 100);

  let y = 720;
  const row = (k: string, v: string) => { page.drawText(k, { x: 60, y, size: 9, font: bold, color: MUTED }); y = wrap(page, v || "-", { x: 170, y, width: 365, size: 11, font: sans, gap: 4 }) - 6; };
  row("BILLED TO", [b?.billing_name, b?.billing_address].filter(Boolean).join(", "));
  if (b?.vat_number) row("VAT NUMBER", b.vat_number);
  if (b?.po_number) row("PURCHASE ORDER", b.po_number);
  row("EVENT", `${venue.short_name ? `${venue.short_name} - ` : ""}${venue.name}`);
  row("ISSUED", inv.issued_on);
  row("DUE", inv.due_on);
  y -= 14;
  page.drawLine({ start: { x: 60, y }, end: { x: 535, y }, thickness: 0.6, color: MUTED });
  y -= 22;
  page.drawText("DESCRIPTION", { x: 60, y, size: 9, font: bold, color: MUTED });
  page.drawText("AMOUNT", { x: 470, y, size: 9, font: bold, color: MUTED });
  y -= 20;
  wrap(page, inv.description, { x: 60, y, width: 380, size: 12, font: sans });
  page.drawText(clean(amount), { x: 470, y, size: 12, font: sans, color: NAVY });
  y -= 40;
  page.drawLine({ start: { x: 60, y }, end: { x: 535, y }, thickness: 0.6, color: MUTED });
  y -= 24;
  page.drawText("TOTAL (excl. VAT)", { x: 330, y, size: 10, font: bold, color: MUTED });
  page.drawText(clean(amount), { x: 470, y, size: 14, font: bold, color: NAVY });
  y -= 50;
  y = wrap(page, inv.status === "paid" ? `Paid${inv.paid_at ? ` on ${inv.paid_at.slice(0, 10)}` : ""}. Thank you.` :
    "Pay by bank transfer within 14 days and quote the invoice number. Bank details: [BANK DETAILS]. Questions: [BILLING CONTACT].", { x: 60, y, width: 475, size: 10, font: sans, color: MUTED });
  wrap(page, "VAT is added where it applies. This invoice was generated by Plenary.", { x: 60, y: y - 6, width: 475, size: 9, font: sans, color: MUTED });
  return pdfResponse(await doc.save(), `plenary-${inv.number}.pdf`);
}
